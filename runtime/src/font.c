/* ---- glyph blit ----------------------------------------------------------- */
static void draw_glyph(jref g, int x, int y, int ch, uint32_t argb) {
    if (ch < 0x20 || ch > 0x7F) ch = '?';
    const unsigned char *gl = FONT8X8[ch - 0x20];
    for (int row = 0; row < GLYPH_H; row++)
        for (int col = 0; col < GLYPH_W; col++)
            if ((gl[row] >> col) & 1) j_gfx_plot(g, x + col, y + row, argb);
}

