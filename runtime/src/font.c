/* MIDP anchor bits (mirror lcdui.c). */
enum { FA_HCENTER = 1, FA_VCENTER = 2, FA_LEFT = 4, FA_RIGHT = 8,
       FA_TOP = 16, FA_BOTTOM = 32, FA_BASELINE = 64 };

/* ---- Font ----------------------------------------------------------------- */
/* One shared Font per process is plenty (metrics are constant). */
static FontObj *g_default_font;
static jref     g_current_font;   /* Graphics' selected font (round-tripped) */

static jref font_singleton(void) {
    if (!g_default_font) {
        g_default_font = (FontObj *)j_new(&CLASS_javax_microedition_lcdui_Font);
        g_default_font->face = 0; g_default_font->style = 0; g_default_font->size = 0;
    }
    return (jref)g_default_font;
}

