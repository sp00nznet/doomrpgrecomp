void m_javax_microedition_lcdui_Graphics__drawString__Ljava_lang_StringIII__V(
        jref this_, jref str, jint x, jint y, jint anchor) {
    if (!str) return;
    int n = j_string_length(str);
    int w = GLYPH_W * n;
    if (anchor & FA_HCENTER)      x -= w / 2;
    else if (anchor & FA_RIGHT)   x -= w;
    if (anchor & (FA_BOTTOM | FA_BASELINE)) y -= GLYPH_H;
    else if (anchor & FA_VCENTER) y -= GLYPH_H / 2;
    uint32_t argb = j_gfx_color(this_);
    char *c = j_string_to_cstr(str);
    for (int i = 0; i < n; i++) draw_glyph(this_, x + i * GLYPH_W, y, (unsigned char)c[i], argb);
    free(c);
}
void m_javax_microedition_lcdui_Graphics__drawSubstring__Ljava_lang_StringIIIII__V(
        jref this_, jref str, jint off, jint len, jint x, jint y, jint anchor) {
    if (!str) return;
    int w = GLYPH_W * len;
    if (anchor & FA_HCENTER)      x -= w / 2;
    else if (anchor & FA_RIGHT)   x -= w;
    if (anchor & (FA_BOTTOM | FA_BASELINE)) y -= GLYPH_H;
    else if (anchor & FA_VCENTER) y -= GLYPH_H / 2;
    uint32_t argb = j_gfx_color(this_);
    char *c = j_string_to_cstr(str);
    int total = j_string_length(str);
    for (int i = 0; i < len && off + i < total; i++)
        draw_glyph(this_, x + i * GLYPH_W, y, (unsigned char)c[off + i], argb);
    free(c);
}
