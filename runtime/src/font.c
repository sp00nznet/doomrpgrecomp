/*
 * font.c -- javax.microedition.lcdui.Font + Graphics text drawing.
 *
 * J2ME's system font is device-defined; we render all of it with one built-in
 * 8x8 bitmap font (public-domain "font8x8_basic"). A Font object just records
 * the requested face/style/size; metrics are fixed (8x8, fixed pitch). Games
 * that ship their own bitmap font (Doom II RPG's Font.rff, etc.) draw it via
 * Image/drawRegion and don't touch this -- this covers the ones that call
 * Graphics.drawString with the system Font (e.g. Wolfenstein RPG).
 */
